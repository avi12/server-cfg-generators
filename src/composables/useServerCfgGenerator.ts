import { REPO_URL } from "@/constants/links";
import {
  CvarType,
  isCvarSection,
  type CvarEntry,
  type CvarItem,
  type CvarOption,
  type CvarValueMap
} from "@/types/cvars";
import { getDefaultValue, isCvarOption, isEmptyValue, isRequired } from "@/utils/cvars";
import { downloadTextFile } from "@/utils/download";
import { reactive, ref } from "vue";

const REGEX_LINK = /\[(.*?)]\((.*?)\)/g;
const REGEX_BOLD = /\*(.*)\*/g;
const NEWLINE = "\r\n";
const CVAR_LOG = "log";
const CVAR_VOICEENABLE = "sv_voiceenable";
const VALUE_PAD_EXTRA = 2;
const TEXT_QUOTES_LENGTH = 2;

interface UseCfgOptions {
  cvars: CvarEntry[];
  gameName: string;
  tutorialUrl?: string;
}

// Switches start at their default; every other field starts empty so the
// user picks a value or opts into the default explicitly
function getInitialValues(items: CvarItem[]) {
  const map: CvarValueMap = {};
  for (const item of items) {
    if (item.defaultValue === undefined || item.defaultValue === null) {
      continue;
    }

    const isBooleanLike = typeof item.defaultValue === "boolean" || item.defaultValue === "on";
    map[item.cvar] = isBooleanLike ? item.defaultValue === true || item.defaultValue === "on" : "";
  }
  return map;
}

export function useServerCfgGenerator({ cvars, gameName, tutorialUrl }: UseCfgOptions) {
  const cvarItems = cvars.filter((entry): entry is CvarItem => !isCvarSection(entry));

  const values = reactive<CvarValueMap>(getInitialValues(cvarItems));
  const isAlign = ref(false);
  const isError = ref(false);

  function toHtml(tutorial: string) {
    return tutorial
      .replace(REGEX_LINK, "<a href=\"$2\" target=\"_blank\" rel=\"noopener noreferrer\">$1</a>")
      .replace(REGEX_BOLD, "<span class=\"font-weight-bold\">$1</span>");
  }

  function useDefaultAll() {
    for (const item of cvarItems) {
      const isCheckbox = item.type === CvarType.Checkbox;
      if (isCheckbox || !isEmptyValue(values[item.cvar])) {
        continue;
      }

      const defaultValue = getDefaultValue(item);
      if (defaultValue !== undefined) {
        values[item.cvar] = defaultValue;
      }
    }
    isError.value = false;
  }

  function findEmptyCvar() {
    return cvarItems.find(item => isRequired(item) && isEmptyValue(values[item.cvar]))?.cvar;
  }

  function generate() {
    isError.value = findEmptyCvar() !== undefined;

    if (isError.value) {
      return;
    }

    const flattened: CvarValueMap = {};
    for (const [key, value] of Object.entries(values)) {
      flattened[key] = isCvarOption(value) ? value.value : value;
    }

    const lines = [`// Made by Avi (${REPO_URL})`, `// Generated by ${location.href}`];
    if (tutorialUrl) {
      lines.push(`// Full ${gameName} server tutorial: ${tutorialUrl}`);
    }

    const widths = computeWidths({
      items: cvarItems,
      values: flattened
    });
    for (const entry of cvars) {
      if (isCvarSection(entry)) {
        lines.push(NEWLINE, `// ${entry.title}`);
        continue;
      }

      const line = buildLine({
        item: entry,
        raw: flattened[entry.cvar],
        widths,
        align: isAlign.value
      });
      lines.push(line);
    }

    lines.push("", "", "exec banned_user.cfg", "exec banned_ips.cfg", "writeid", "writeip");
    downloadTextFile(lines.join(NEWLINE), "server.cfg", "text/plain");
  }

  return {
    cvars,
    values,
    isAlign,
    isError,
    toHtml,
    useDefaultAll,
    generate,
    findEmptyCvar
  };
}

interface Widths {
  cvar: number;
  value: number;
}

interface ComputeWidthsArgs {
  items: CvarItem[];
  values: CvarValueMap;
}

function computeWidths({ items, values }: ComputeWidthsArgs) {
  const widths: Widths = {
    cvar: 0,
    value: 0
  };
  for (const item of items) {
    const raw = values[item.cvar];
    const valueLength = computeRawLength({
      item,
      raw
    });
    widths.value = Math.max(widths.value, valueLength);
    widths.cvar = Math.max(widths.cvar, item.cvar.length);
  }
  widths.value += VALUE_PAD_EXTRA;
  return widths;
}

interface RawArgs {
  item: CvarItem;
  raw: CvarValueMap[string];
}

function computeRawLength({ item, raw }: RawArgs) {
  switch (item.type) {
    case CvarType.Number:
    case CvarType.Text:
    case CvarType.Email:
    case CvarType.Select:
      return String(raw ?? "").length;
    case CvarType.Checkbox:
      return item.cvar === CVAR_LOG ? String(raw ?? "").length : 1;
  }
}

interface BuildLineArgs {
  item: CvarItem;
  raw: CvarValueMap[string];
  widths: Widths;
  align: boolean;
}

function buildLine({ item, raw, widths, align }: BuildLineArgs) {
  const padCvar = " ".repeat(Math.max(0, widths.cvar - item.cvar.length));
  const value = formatValue({
    item,
    raw
  });
  const valueLength = computeFormattedLength({
    item,
    raw,
    value
  });
  const padValue = " ".repeat(Math.max(0, widths.value - valueLength));
  const tutorial = item.tutorial.replace("to On", "to 1").replace(REGEX_LINK, "$1 ($2)");
  const specialValues = item.specialValues ? `. Special values: ${optionsToText(item.specialValues)}` : "";

  let line = item.cvar + " ";
  if (align) {
    line += padCvar;
  }

  line += `${value} `;

  if (align) {
    line += padValue;
  }

  line += `// ${tutorial}${specialValues}`;

  const suffix = buildOptionsSuffix({
    item,
    tutorial
  });
  if (suffix) {
    line += suffix;
  }

  return line;
}

interface FormattedLengthArgs {
  item: CvarItem;
  raw: CvarValueMap[string];
  value: string;
}

function computeFormattedLength({ item, raw, value }: FormattedLengthArgs) {
  const isQuotedText = item.type === CvarType.Text || item.type === CvarType.Email;
  if (isQuotedText) {
    return String(raw ?? "").length + TEXT_QUOTES_LENGTH;
  }

  const isLogCheckbox = item.type === CvarType.Checkbox && item.cvar === CVAR_LOG;
  if (isLogCheckbox) {
    return String(value).length;
  }

  if (item.type === CvarType.Checkbox) {
    return 1;
  }

  return String(value).length;
}

interface OptionsSuffixArgs {
  item: CvarItem;
  tutorial: string;
}

function buildOptionsSuffix({ item, tutorial }: OptionsSuffixArgs) {
  const isVoiceEnable = item.type === CvarType.Select && item.cvar === CVAR_VOICEENABLE;
  if (isVoiceEnable) {
    return `. Options: ${optionsToText([
      {
        text: "Enable",
        value: 1
      },
      {
        text: "Disable",
        value: 0
      }
    ])}`;
  }

  if (item.type === CvarType.Select && item.options) {
    const text = item.cvar === CVAR_LOG ? "(on/off)" : `Options: ${optionsToText(item.options)}`;
    return `. ${text}`;
  }

  if (item.type === CvarType.Checkbox) {
    const match = (tutorial.match(/allow|abl/) ?? ["abl"])[0];
    const yesNo = match === "allow" ? ["Allow", "Disallow"] : ["Enable", "Disable"];
    const optionValues: CvarOption[] = item.cvar === CVAR_LOG
      ? [
        {
          text: yesNo[0],
          value: "on"
        },
        {
          text: yesNo[1],
          value: "off"
        }
      ]
      : [
        {
          text: yesNo[0],
          value: 1
        },
        {
          text: yesNo[1],
          value: 0
        }
      ];
    return `. Options: ${optionsToText(optionValues)}`;
  }

  return "";
}

function formatValue({ item, raw }: RawArgs) {
  switch (item.type) {
    case CvarType.Text:
      return `"${String(raw ?? "").replace(/"/g, "\\\"")}"`;
    case CvarType.Email:
      return `"${raw ?? ""}"`;
    case CvarType.Checkbox:
      if (item.cvar === CVAR_LOG) {
        return raw ? "on" : "off";
      }

      return raw ? "1" : "0";
    default:
      return String(raw ?? "");
  }
}

function optionsToText(options: CvarOption[]) {
  return options.map(option => `${option.text} = ${option.value}`).join(", ");
}
